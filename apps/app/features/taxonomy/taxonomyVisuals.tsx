export function taxonomyIconKey(value: string | null | undefined): TaxonomyIconKey {
  return TAXONOMY_ICON_KEYS.includes(value as TaxonomyIconKey)
    ? value as TaxonomyIconKey
    : DEFAULT_TAXONOMY_ICON;
}

export function TaxonomyIcon({ iconKey, ...props }: IconProps & { iconKey?: string | null }) {
  const Icon = iconByKey[taxonomyIconKey(iconKey)];
  return <Icon {...props} />;
}
